// Reproducible, checked-in browser assets. Serving app/ needs no Node/npm or CDN.
import {build} from 'esbuild';
import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {dirname,join,relative,resolve,sep} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const sourceRoot=join(root,'app/pptx-import'),outputRoot=join(sourceRoot,'vendor');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const slash=value=>value.split(sep).join('/');
const require=createRequire(join(root,'package.json'));
function packageRoot(name,from=root){
 const resolver=from===root?require:createRequire(join(from,'package.json'));
 try{return dirname(resolver.resolve(name+'/package.json'));}catch{}
 let current=dirname(resolver.resolve(name));
 for(let count=0;count<12;count++){
  try{if(require(join(current,'package.json')).name===name)return current;}catch{}
  const parent=dirname(current);if(parent===current)break;current=parent;
 }
 throw Error('Cannot locate package: '+name);
}
async function allFiles(directory){
 const entries=await readdir(directory,{withFileTypes:true}).catch(error=>error.code==='ENOENT'?[]:Promise.reject(error));
 return (await Promise.all(entries.map(async entry=>entry.isDirectory()?allFiles(join(directory,entry.name)):join(directory,entry.name)))).flat();
}

export async function buildPptxImport({check=false}={}){
 const packages={},roots={};
 for(const name of ['fflate','@xmldom/xmldom','@aiden0z/pptx-renderer','esbuild','jszip','echarts','zrender']){
  roots[name]=packageRoot(name);
  packages[name]=JSON.parse(await readFile(join(roots[name],'package.json'),'utf8')).version;
 }
 roots.tslib=packageRoot('tslib',roots.zrender);
 packages.tslib=JSON.parse(await readFile(join(roots.tslib,'package.json'),'utf8')).version;
 // The DOM adapter is deliberately tied to this exact renderer's IR and markup.
 if(packages['@aiden0z/pptx-renderer']!=='1.3.0')throw Error('PPTX preview renderer must be exactly 1.3.0');
 const rendererVersion='export default Object.freeze('+JSON.stringify({id:'aiden0z-pptx-renderer',version:packages['@aiden0z/pptx-renderer']})+');\n';
 const generated=new Map([['renderer-version.js',Buffer.from(rendererVersion)]]);
 const sources=new Set(['app/pptx-import/preview-frame.html','tools/build-pptx-import.mjs','package-lock.json']);
 const buildCommon={absWorkingDir:root,bundle:true,platform:'browser',target:'es2022',minify:true,write:false,metafile:true,logLevel:'silent'};
 const licenses=[
  ['@xmldom/xmldom','LICENSE','xmldom-MIT.txt'],['fflate','LICENSE','fflate-MIT.txt'],
  ['@aiden0z/pptx-renderer','LICENSE','pptx-renderer-Apache-2.0.txt'],
  ['@aiden0z/pptx-renderer','THIRD_PARTY_NOTICES.md','THIRD_PARTY_NOTICES.md'],
  ['@aiden0z/pptx-renderer','licenses/mtx-decompressor-MPL-2.0.txt','licenses/mtx-decompressor-MPL-2.0.txt'],
  ['@aiden0z/pptx-renderer','licenses/ECMA-text-copyright-notice.txt','licenses/ECMA-text-copyright-notice.txt'],
  ['jszip','LICENSE.markdown','jszip-LICENSE.md'],['echarts','LICENSE','echarts-LICENSE.txt'],
  ['echarts','NOTICE','echarts-NOTICE.txt'],['echarts','licenses/LICENSE-d3','licenses/LICENSE-d3'],
  ['zrender','LICENSE','zrender-LICENSE.txt'],['tslib','CopyrightNotice.txt','tslib-CopyrightNotice.txt'],['tslib','LICENSE.txt','tslib-LICENSE.txt']
 ];
 for(const [name,source,dest] of licenses)generated.set('licenses/'+dest,await readFile(join(roots[name],source)));
 const xmlLicense=generated.get('licenses/xmldom-MIT.txt').toString(),zipLicense=generated.get('licenses/fflate-MIT.txt').toString();
 const worker=await build({...buildCommon,entryPoints:['app/pptx-import/worker.js'],format:'esm',outfile:'pptx-worker.js',legalComments:'none',
  banner:{js:`/*! Generated by tools/build-pptx-import.mjs.\n@xmldom/xmldom license:\n${xmlLicense.replaceAll('*/','* /')}\nfflate license:\n${zipLicense.replaceAll('*/','* /')}\n*/`}});
 generated.set('pptx-worker.js',worker.outputFiles[0].contents);
 const preview=await build({...buildCommon,entryPoints:['app/pptx-import/preview-frame.js'],format:'iife',outfile:'preview-frame.js',legalComments:'inline',plugins:[{
  name:'actual-renderer-version',setup(builder){
   builder.onResolve({filter:/^\.\/vendor\/renderer-version\.js$/},()=>({path:'renderer-version',namespace:'onbatang-build'}));
   builder.onLoad({filter:/.*/,namespace:'onbatang-build'},()=>({contents:rendererVersion,loader:'js'}));
  }
 }]});
 const script=preview.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
 const scriptHash=createHash('sha256').update(script).digest('base64');
 const template=await readFile(join(sourceRoot,'preview-frame.html'),'utf8');
 if(template.split('__SCRIPT_HASH__').length!==2||template.split('__PREVIEW_SCRIPT__').length!==2)throw Error('Invalid PPTX preview template');
 generated.set('preview-frame.html',Buffer.from(template.replace('__SCRIPT_HASH__',scriptHash).replace('__PREVIEW_SCRIPT__',()=>script)));
 for(const result of [worker,preview])for(const input of Object.keys(result.metafile.inputs)){
  if(input.startsWith('onbatang-build:')||slash(input).split('/').includes('node_modules'))continue;
  sources.add(slash(input));
 }
 const sourceHashes={};for(const source of [...sources].sort())sourceHashes[source]=sha(await readFile(join(root,source)));
 const outputs={};for(const [name,bytes] of [...generated].sort(([a],[b])=>a.localeCompare(b)))outputs[name]={bytes:bytes.byteLength,sha256:sha(bytes)};
 const manifest={format:1,renderer:{id:'aiden0z-pptx-renderer',version:'1.3.0'},packages:Object.fromEntries(Object.entries(packages).sort(([a],[b])=>a.localeCompare(b))),
  previewScriptSha256:scriptHash,sources:sourceHashes,files:outputs};
 generated.set('BUILD.json',Buffer.from(JSON.stringify(manifest,null,2)+'\n'));
 if(check){
  const actual=(await allFiles(outputRoot)).map(path=>slash(relative(outputRoot,path))).sort(),expected=[...generated.keys()].sort();
  if(JSON.stringify(actual)!==JSON.stringify(expected))throw Error('PPTX vendor file list differs; run npm run build:pptx-import');
  for(const [name,bytes] of generated)if(!Buffer.from(await readFile(join(outputRoot,name))).equals(Buffer.from(bytes)))throw Error('PPTX vendor bytes differ: '+name);
 }else{
  const expected=new Set(generated.keys());
  for(const path of await allFiles(outputRoot))if(!expected.has(slash(relative(outputRoot,path))))throw Error('Unexpected PPTX vendor file; review before replacing: '+slash(relative(outputRoot,path)));
  for(const [name,bytes] of generated){const path=join(outputRoot,name);await mkdir(dirname(path),{recursive:true});await writeFile(path,bytes);}
 }
 return {files:generated.size,rendererVersion:'1.3.0',workerBytes:generated.get('pptx-worker.js').byteLength,previewBytes:generated.get('preview-frame.html').byteLength,
  manifestSha256:sha(generated.get('BUILD.json')),previewScriptSha256:scriptHash};
}

if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
 const unknown=process.argv.slice(2).filter(arg=>arg!=='--check');if(unknown.length)throw Error('Usage: node tools/build-pptx-import.mjs [--check]');
 console.log(JSON.stringify(await buildPptxImport({check:process.argv.includes('--check')})));
}
