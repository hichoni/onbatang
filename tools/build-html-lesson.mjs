import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({ absWorkingDir: root, entryPoints: ['app/html-lesson-runtime.js'], bundle: true, format: 'iife', target: ['es2020'], minify: true, write: false, charset: 'ascii', legalComments: 'none' });
const style = (await Promise.all(['app/pixel-art.css', 'app/gai-app.css', 'app/html-lesson.css'].map(p => readFile(new URL(`../${p}`, import.meta.url), 'utf8')))).join('\n');
await writeFile(new URL('../app/html-lesson-bundle.js', import.meta.url), `// Generated by node tools/build-html-lesson.mjs. Do not edit.\nexport const HTML_LESSON_RUNTIME = ${JSON.stringify(result.outputFiles[0].text)};\nexport const HTML_LESSON_STYLE = ${JSON.stringify(style)};\n`);
console.log('Built self-contained HTML lesson runtime and styles.');
