const SEEN = 'onbatang-whats-new-seen-v1';
// 버전 글자 '0.45' 를 견줄 수 있는 수로
const rank = (v) => String(v).split('.').reduce((n, part) => n * 1000 + (Number(part) || 0), 0);
/** 가장 새 기능의 버전 */
export const latestFeature = () => WHATS_NEW.reduce((best, f) => (rank(f.since) > rank(best) ? f.since : best), '0');
/** 이 기기가 아직 보지 않은 새 기능이 있는가 */
export function hasUnseenFeatures() {
  try { return rank(localStorage.getItem(SEEN) || '0') < rank(latestFeature()); } catch { return false; }
}
/** 새 기능을 다 봤다고 이 기기에 적는다 */
export function markFeaturesSeen() {
  try { localStorage.setItem(SEEN, latestFeature()); } catch { /* 적지 못해도 괜찮다 */ }
}
